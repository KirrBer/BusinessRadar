def generate_recommendation(score, demand_pct, competitors, rent_cost, cluster_name):
    d = "высокий" if demand_pct >= 0.7 else ("средний" if demand_pct >= 0.35 else "низкий")
    c = "много" if competitors >= 5 else ("умеренно" if competitors >= 2 else "мало")

    # полная матрица спрос × конкуренция (чинит пропуск «высокий + умеренная конкуренция»)
    if demand_pct >= 0.7 and competitors >= 5:
        core = ("Спрос высокий, но конкуренция плотная — заходить «в лоб» рискованно, "
                "нужен уникальный формат/ассортимент, чтобы отстроиться от соседей.")
    elif demand_pct >= 0.7 and competitors < 2:
        core = ("Спрос высокий при слабой конкуренции — сильная локация, "
                "можно масштабировать точку и захватывать поток первым.")
    elif demand_pct >= 0.7:                       # 2..4 конкурента — раньше проваливалось в else
        core = ("Спрос высокий, конкуренция умеренная — локация рабочая, "
                "но держи в голове соседей и следи за дифференциацией.")
    elif demand_pct < 0.35 and competitors >= 2:
        core = ("Спрос низкий и конкуренты есть — худший сценарий, "
                "в такую точку заходить не стоит без особой причины.")
    elif demand_pct < 0.35:
        core = ("Спрос низкий, конкурентов мало — ниша пустая, но и денег мало; "
                "подходит только формат с низкой арендой и быстрым выходом в плюс.")
    else:
        core = ("Спрос умеренный — решение зависит от юнит-экономики, "
                "считай окупаемость при текущей аренде.")

    # аренда упоминается НЕЗАВИСИМО от спроса (чинит «ловушку аренды» с высоким pct)
    rent_note = ""
    if rent_cost > 0.66:
        rent_note = (" Учти: высокая аренда давит на маржу — "
                     "точка выходит в плюс только при чеке/обороте выше рынка.")

    return f"Скоринг {score}/10 ({d} спрос, конкурентов {c}). {core}{rent_note} Район: «{cluster_name}»."